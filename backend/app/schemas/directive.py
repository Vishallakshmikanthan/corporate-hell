"""
Pydantic schemas for Executive Command directives.
"""
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class DirectiveRequest(BaseModel):
    directive: str = Field(description="The CEO's executive command or custom instruction")
    company_name: Optional[str] = "HellWorks Inc."
    day: Optional[int] = 1
    cash: Optional[float] = 0.0
    morale: Optional[float] = 50.0
    stress: Optional[float] = 50.0
    employee_count: Optional[int] = 12


class EmployeeQuote(BaseModel):
    employee_name: str
    quote: str
    archetype: Optional[str] = None


class DirectiveResponse(BaseModel):
    title: str = Field(description="Catchy corporate headline for the directive")
    executive_summary: str = Field(description="Satirical executive summary of what happened")
    action_type: str = Field(
        description="Validated game engine action: policy_4day, cut_meetings, morale_boost, audit_spending, trigger_incident, bonus_all, custom"
    )
    action_payload: Optional[Dict[str, Any]] = Field(default_factory=dict)
    cash_delta: float = 0.0
    morale_delta: float = 0.0
    stress_delta: float = 0.0
    quotes: List[EmployeeQuote] = Field(default_factory=list)
    confidence: float = Field(default=0.9, ge=0, le=1)
    source: Literal["ai", "fallback"] = Field(
        default="fallback", description="Whether generated by NVIDIA GLM-5.3 or deterministic rule engine"
    )
