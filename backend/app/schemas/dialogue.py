"""
Pydantic schemas for AI dialogue requests and validated responses.
"""
from typing import List, Literal, Optional
from pydantic import BaseModel, Field

EmotionType = Literal[
    'neutral',
    'happy',
    'excited',
    'celebratory',
    'smug',
    'sad',
    'angry',
    'frustrated',
    'confused',
    'exhausted',
    'panicked',
    'embarrassed',
]


class DialogueContext(BaseModel):
    cash: Optional[float] = None
    morale: Optional[float] = None
    reputation: Optional[float] = None
    recent_event: Optional[str] = None
    player_decision: Optional[str] = None
    open_incidents: Optional[List[str]] = None


class DialogueRequest(BaseModel):
    employee_id: str
    employee_name: str
    archetype: str
    role: str
    department: str
    bio: str
    morale: float = Field(ge=0, le=100)
    stress: float = Field(ge=0, le=100)
    energy: float = Field(ge=0, le=100)
    trust: float = Field(ge=0, le=100)
    current_activity: str
    current_task: Optional[str] = None
    context: Optional[DialogueContext] = None


class DialogueResponse(BaseModel):
    dialogue: str = Field(description="Characterful spoken line or response")
    emotion: EmotionType = Field(default="neutral", description="Expressive emotion reaction")
    thought: str = Field(description="Short inner thought bubble (max 10 words)")
    referencedEventIds: List[str] = Field(default_factory=list)
    suggestedAction: Optional[str] = Field(
        default=None, description="Non-authoritative proposed action"
    )
    confidence: float = Field(default=0.9, ge=0, le=1)
    source: Literal["ai", "fallback"] = Field(
        default="fallback", description="Whether generated by NVIDIA LLM or local deterministic template"
    )
